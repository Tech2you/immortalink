import {test} from 'node:test';
import assert from 'node:assert/strict';
import {copyOne,digests,readBounded,objectKeys,validateCopy,runBackup,createBackupHandler} from './core.mjs';
import {createSource,createDestination} from './transport.mjs';
const bytes=new TextEncoder().encode('Generated Heiro recovery check. No family content.');
const job={kind:'copy',fingerprint:'a'.repeat(64),object_id:'00000000-0000-4000-8000-000000000001',bucket:'memory_photos',
  object_name:'generated/photo.png',source_updated_at:'2026-11-06T00:00:00Z',byte_size:bytes.length,source_etag:digests(bytes).md5};
function fixture(){const files=new Map();let downloads=0;
 return {files,get downloads(){return downloads;},source:{download:async()=>{downloads++;return new Response(bytes);}},isCurrent:async()=>true,
 destination:{head:async key=>{const o=files.get(key);return o?{size:o.bytes.length,etag:o.hash.md5,...o.hash}:null;},
 putBytes:async(key,data,hash)=>{files.set(key,{bytes:data.slice(),hash});},putJson:async(key,value)=>{files.set(key,{json:value});},
 remove:async key=>files.delete(key)}};}
test('verified copy restores identical generated bytes and records independent recovery metadata',async()=>{
 const f=fixture(),hash=await copyOne({job,...f}),keys=objectKeys(job.fingerprint);
 assert.deepEqual(hash,digests(bytes));assert.deepEqual(f.files.get(keys.data).bytes,bytes);
 assert.deepEqual(digests(f.files.get(keys.data).bytes),hash);
 assert.equal(f.files.get(keys.metadata).json.object_name,job.object_name);
 assert.equal(f.files.get(keys.metadata).json.sha256,hash.sha256);
 assert.equal(JSON.stringify(f.files.get(keys.metadata)).includes('Bearer'),false);
});
test('retry after successful object write reuses data without another download',async()=>{
 const f=fixture();await copyOne({job,...f});await copyOne({job,...f});assert.equal(f.downloads,1);
});
test('partial upload or wrong checksum cannot become a verified backup',async()=>{
 const f=fixture();f.destination.head=async()=>({size:1,etag:'b'.repeat(32),md5:'b'.repeat(32),sha256:'c'.repeat(64)});
 await assert.rejects(copyOne({job,...f}),/VERIFY_FAILED/);assert.equal(f.downloads,0);
});
test('changed source during download never writes a mislabeled backup',async()=>{
 const f=fixture();let n=0;f.isCurrent=async()=>++n===1;
 await assert.rejects(copyOne({job,...f}),/SOURCE_FAILED/);assert.equal(f.files.size,0);
});
test('known source checksum mismatch is rejected',async()=>{
 const f=fixture();await assert.rejects(copyOne({job:{...job,source_etag:'0'.repeat(32)},...f}),/VERIFY_FAILED/);assert.equal(f.files.size,0);
});
test('bounded reader rejects short, oversized and falsely advertised bodies',async()=>{
 await assert.rejects(readBounded(new Response(bytes),bytes.length-1),/VERIFY_FAILED/);
 await assert.rejects(readBounded(new Response(bytes),bytes.length+1),/VERIFY_FAILED/);
 await assert.rejects(readBounded(new Response(bytes,{headers:{'content-length':'999'}}),bytes.length),/VERIFY_FAILED/);
 await assert.rejects(readBounded(new Response(bytes),60*1024*1024),/VERIFY_FAILED/);
});
test('source paths, buckets and destinations cannot be chosen by untrusted jobs',async()=>{
 for(const patch of [{bucket:'other'},{object_name:'../private'},{object_name:'x/./y'},{byte_size:-1},{byte_size:Infinity},{fingerprint:'../../x'}])assert.throws(()=>validateCopy({...job,...patch}));
 assert.throws(()=>createDestination({accountId:'attacker.example',bucket:'x',sign:()=>{}}));
 const calls=[],source=createSource({serviceKey:'test-key',fetcher:async(url,init)=>{calls.push({url,init});return new Response(bytes);}});
 await source.download({...job,object_name:'x/a?b#c%2F.png'});
 assert.match(calls[0].url,/x\/a%3Fb%23c%252F.png$/);assert.equal(calls[0].init.method,'GET');assert.equal(calls[0].init.redirect,'error');
 await assert.rejects(source.rpc('delete_account',{}),/BACKUP_UNAVAILABLE/);
});
test('destination uses fixed private S3 host, checksums, create-only data writes and no redirects',async()=>{
 const calls=[],d=createDestination({accountId:'a'.repeat(32),bucket:'heiro-media-backup-launch',sign:async(url,init)=>new Request(url,init),
 fetcher:async r=>{calls.push(r);return new Response(null,{status:200});}});
 await d.putBytes(objectKeys(job.fingerprint).data,bytes,digests(bytes));
 assert.equal(calls[0].method,'PUT');assert.equal(calls[0].redirect,'error');assert.equal(calls[0].headers.get('if-none-match'),'*');
 assert.equal(calls[0].headers.get('content-md5'),Buffer.from(digests(bytes).md5,'hex').toString('base64'));
 assert.equal(calls[0].headers.get('cache-control'),'private, no-store, no-transform');
 assert.equal(calls[0].headers.get('accept-encoding'),'identity');
 await assert.rejects(d.remove('status/latest.json'),/VERIFY_FAILED/);
 await assert.rejects(d.putJson('../../elsewhere',{}),/VERIFY_FAILED/);
});
test('HTTP worker requires single-use DB authority and ignores caller body',async()=>{
 let claims=0,runs=0;const f=fixture();
 const handler=createBackupHandler({enabled:true,backend:{rpc:async()=>++claims===1},...f,run:async()=>{runs++;}});
 assert.equal((await handler(new Request('https://example',{method:'POST'}))).status,401);
 const req=()=>new Request('https://example',{method:'POST',headers:{'x-backup-run-token':'a'.repeat(64)},body:'{"bucket":"attacker","url":"http://127.0.0.1"}'});
 assert.equal((await handler(req())).status,202);assert.equal((await handler(req())).status,401);assert.equal(runs,1);
 assert.equal((await createBackupHandler() (req())).status,503);
});
test('hosted runtime does not need an implicit global Buffer for upload signing',async()=>{
 const original=globalThis.Buffer;let headers;
 const d=createDestination({accountId:'a'.repeat(32),bucket:'heiro-media-backup-launch',sign:async(_url,init)=>{headers=init.headers;return init;},fetcher:async()=>({ok:true,body:null})});
 try {globalThis.Buffer=undefined;await d.putBytes(objectKeys(job.fingerprint).data,bytes,digests(bytes));assert.equal(typeof headers['content-md5'],'string');}
 finally {globalThis.Buffer=original;}
});
test('failed copies never acknowledge completion or write success manifest',async()=>{
 const f=fixture(),calls=[];f.source.download=async()=>{throw new Error('SOURCE_FAILED');};
 const backend={rpc:async(name,args)=>{calls.push({name,args});if(name==='next_media_backup_work')return job;if(name==='media_backup_source_current')return true;return true;}};
 const result=await runBackup({backend,...f,token:'test'});assert.equal(result.error,'SOURCE_FAILED');
 assert.equal(calls.some(c=>c.name==='complete_media_backup_work'),false);assert.equal(f.files.size,0);
 assert.equal(calls.at(-1).args.p_error,'SOURCE_FAILED');
});
test('incomplete inventories are never advertised as complete backups',async()=>{
 const f=fixture(),backend={rpc:async name=>name==='next_media_backup_work'?null:name==='media_backup_manifest'?{format:1,missing:1,entries:[]}:true};
 const result=await runBackup({backend,...f,token:'test'});assert.equal(result.manifestSaved,false);assert.equal(f.files.size,0);
});
test('batch bounds, complete daily manifest and delayed backup-only deletion',async()=>{
 const f=fixture(),calls=[];let n=0;
 const backend={rpc:async(name,args)=>{calls.push({name,args});
 if(name==='next_media_backup_work')return ++n===1?job:null;
 if(name==='media_backup_source_current'||name==='complete_media_backup_work')return true;
 if(name==='media_backup_manifest')return {format:1,captured_at:'2026-11-06T01:00:00Z',missing:0,entries:[job]};return true;}};
 const result=await runBackup({backend,...f,token:'test'});assert.equal(result.copied,1);assert.equal(result.manifestSaved,true);
 assert.equal(f.files.get('status/latest.json').json.objects,1);assert.equal(calls.at(-1).args.p_manifest,true);
});
