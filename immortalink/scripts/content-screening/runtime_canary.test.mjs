import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createRuntimeCanary, createCanaryNormalizerLoader } from './runtime_canary.mjs';

const sample = Buffer.from('GENERATED_FIXTURE_ONLY');
const digest = createHash('sha256').update(sample).digest('hex');
const key = 'test-only-service-key-not-a-real-secret';
const serviceKeySha256 = createHash('sha256').update(key).digest('hex');
const fixtures = Object.fromEntries(['small', 'large', 'batch'].map(name => [name, { bytes: sample.length, sha256: digest, count: name === 'batch' ? 4 : 1 }]));
const req = (fixture = 'small', body = sample, authorization = `Bearer ${key}`) => new Request(`https://example.invalid/canary?fixture=${fixture}`, {
  method: 'POST', headers: { authorization, 'x-heiro-canary-key': authorization.replace(/^Bearer /, ''), 'content-type': 'application/octet-stream' }, body });
function config(extra = {}) {
  let loads = 0, decoded = 0; const outputs = [];
  return { counts: () => ({ loads, decoded }), outputs, handler: createRuntimeCanary({ serviceKeySha256,
    fixtures, expiresAt: Date.now() + 60000, loadNormalizer: async () => {
      loads++; return async () => { decoded++; const bytes = new Uint8Array([255, 216, 255, 217]); outputs.push(bytes); return { bytes, mime: 'image/jpeg' }; };
    }, ...extra }) };
}

test('runtime canary rejects anonymous/app credentials, expired sessions, methods and unlisted fixtures before decoding', async () => {
  const c = config();
  for (const auth of ['', 'Bearer app-user-jwt', 'Bearer ' + key + 'x']) assert.equal((await c.handler(req('small', sample, auth))).status, 401);
  assert.equal((await c.handler(new Request('https://example.invalid/canary', { headers: { authorization: `Bearer ${key}`, 'x-heiro-canary-key': key } }))).status, 405);
  assert.equal((await c.handler(req('other'))).status, 400);
  assert.equal((await config({ expiresAt: 1 }).handler(req())).status, 410);
  assert.deepEqual(c.counts(), { loads: 0, decoded: 0 });
});

test('canary requires the pinned secret even if a gateway bearer is present, and configuration fails closed', async () => {
  const c = config();
  for (const headers of [
    { authorization: `Bearer ${key}` },
    { authorization: `Bearer ${key}`, 'x-heiro-canary-key': serviceKeySha256 },
    { 'x-heiro-canary-key': 'x'.repeat(8193) },
  ]) assert.equal((await c.handler(new Request('https://example.invalid/canary', { method: 'POST', headers }))).status, 401);
  for (const pin of [undefined, '', key, 'not-a-digest']) assert.throws(() => config({ serviceKeySha256: pin }), /INVALID_CANARY_CONFIG/);
  assert.deepEqual(c.counts(), { loads: 0, decoded: 0 });
});

test('runtime canary accepts only exact hashed generated bytes and bounds actual streamed bytes', async () => {
  const c = config();
  const wrong = Buffer.from(sample); wrong[0] = 0;
  for (const body of [wrong, sample.subarray(0, -1), Buffer.concat([sample, Buffer.from('extra')])]) assert.notEqual((await c.handler(req('small', body))).status, 200);
  assert.deepEqual(c.counts(), { loads: 0, decoded: 0 });
});

test('runtime canary retains and serializes a bounded batch, returns metrics only and clears outputs', async () => {
  const c = config(); const response = await c.handler(req('batch')); const result = await response.json();
  assert.equal(response.status, 200); assert.equal(result.completed, 4);
  assert.equal(result.outputBytes, 16); assert(result.serializedBytes > 0);
  assert.equal(JSON.stringify(result).includes('GENERATED'), false);
  assert(c.outputs.every(b => b.every(v => v === 0)));
  assert.equal((await c.handler(req('batch'))).status, 429);
  assert.deepEqual(c.counts(), { loads: 1, decoded: 4 });
});

test('runtime canary declines concurrent work and does not repeat a failed processor', async () => {
  let release; const waiting = new Promise(resolve => { release = resolve; });
  const c = config({ loadNormalizer: async () => { await waiting; throw new Error('private detail'); } });
  const first = c.handler(req()); await new Promise(resolve => setImmediate(resolve));
  assert.equal((await c.handler(req('large'))).status, 429);
  release(); assert.deepEqual(await (await first).json(), { code: 'CANARY_FAILED' });
  assert.equal((await c.handler(req())).status, 429);
});

test('stage diagnostics contain only fixed labels and observer failures cannot alter authorization', async () => {
  const stages = [];
  const c = config({ onStage: (...args) => stages.push(args) });
  assert.equal((await c.handler(req())).status, 200);
  assert.deepEqual(stages, ['request_received', 'authorized', 'body_started', 'body_first_chunk',
    'body_ready', 'fixture_verified', 'normalizer_ready', 'photo_started', 'photo_ready', 'serialized'].map(s => [s]));
  const broken = config({ onStage: () => { throw new Error('observer failure'); } });
  assert.equal((await broken.handler(req('small', sample, 'Bearer invalid'))).status, 401);
  assert.equal((await broken.handler(req())).status, 200);
});

test('binary diagnostics identify download and initialization without leaking bytes', async () => {
  const stages = [];
  const load = createCanaryNormalizerLoader({ sha256: digest, bytes: sample.length,
    createPreparer: async () => 'normalizer', fetcher: async () => new Response(sample),
    onStage: (...args) => stages.push(args) });
  await load();
  assert.deepEqual(stages, ['binary_fetch_started', 'binary_headers_received', 'binary_first_chunk',
    'binary_verified', 'wasm_init_started', 'wasm_init_ready'].map(s => [s]));
});

test('binary loader uses fixed pinned URL and verified bytes, never retries, and refuses altered/oversized code', async () => {
  for (const valid of [true, false]) {
    let calls = 0, initialized = 0;
    const load = createCanaryNormalizerLoader({ sha256: digest, bytes: sample.length,
      createPreparer: async bytes => { initialized++; assert.deepEqual(Buffer.from(bytes), sample); return 'normalizer'; },
      fetcher: async (url, opts) => {
        calls++; assert.equal(url, 'https://cdn.jsdelivr.net/npm/@imagemagick/magick-wasm@0.0.45/dist/x86/magick.wasm');
        assert.equal(opts.redirect, 'error'); assert.equal(opts.headers, undefined);
        return new Response(valid ? sample : Buffer.alloc(sample.length));
      } });
    if (valid) { assert.equal(await load(), 'normalizer'); assert.equal(await load(), 'normalizer'); }
    else { await assert.rejects(load()); await assert.rejects(load()); }
    assert.equal(calls, 1); assert.equal(initialized, valid ? 1 : 0);
  }
  const load = createCanaryNormalizerLoader({ sha256: digest, bytes: sample.length,
    createPreparer: () => assert.fail('Oversized binary must not execute'),
    fetcher: async () => new Response(Buffer.alloc(sample.length + 1)) });
  await assert.rejects(load());
});
